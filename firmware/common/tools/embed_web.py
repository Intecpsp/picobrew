#!/usr/bin/env python3
"""Package common device website into deterministic gzip and safe flash assets."""
import argparse,gzip,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
ASSETS=[('index.html','text/html; charset=utf-8'),('device.js','application/javascript; charset=utf-8'),
    ('app.js','application/javascript; charset=utf-8'),('api-explorer.js','application/javascript; charset=utf-8'),
    ('history.js','application/javascript; charset=utf-8'),('style.css','text/css; charset=utf-8'),
    ('favicon.ico','image/x-icon')]
def products():
    source=['// Generated by tools/embed_web.py. Do not edit.', '#include "picobrew/common_web.h"',
        '#include <string.h>','#if defined(ESP8266)','#include <pgmspace.h>','#define PICO_WEB_FLASH PROGMEM','#else','#define PICO_WEB_FLASH','#endif','namespace {']
    outputs={};entries=[]
    for index,(name,kind) in enumerate(ASSETS):
        raw=(ROOT/'web'/name).read_bytes();packed=bytearray(gzip.compress(raw,compresslevel=9,mtime=0));packed[9]=255;packed=bytes(packed)
        source.append(f'static const uint8_t asset_{index}[] PICO_WEB_FLASH = {{')
        source.extend('    '+','.join(f'0x{value:02x}' for value in packed[i:i+20])+',' for i in range(0,len(packed),20));source.append('};')
        entries.append(dict(source=name,content_type=kind,content_encoding='gzip',length=len(packed),source_length=len(raw),
            source_sha256=hashlib.sha256(raw).hexdigest(),sha256=hashlib.sha256(packed).hexdigest(),file_path='/common/web/'+name+'.gz'))
        outputs[ROOT/'firmware/web'/f'{name}.gz']=packed
    source+=['struct Entry {const char* path;const uint8_t* bytes;size_t length;};','static const Entry entries[] = {']
    source += ['    {"'+e['file_path']+'",asset_'+str(i)+','+str(e['length'])+'},' for i,e in enumerate(entries)]
    source += ['};','int asset_open(void*,const char* path,size_t length){',
        '    if(!path)return PICO_HTTP_IO_ERROR;',
        '    for(size_t i=0;i<sizeof(entries)/sizeof(entries[0]);++i)if(strcmp(path,entries[i].path)==0)return length==entries[i].length?static_cast<int>(i):PICO_HTTP_IO_ERROR;',
        '    return PICO_HTTP_IO_ERROR;','}',
        'int asset_read(void*,int handle,size_t offset,uint8_t* destination,size_t length){',
        '    if(handle<0||static_cast<size_t>(handle)>=sizeof(entries)/sizeof(entries[0])||!destination)return PICO_HTTP_IO_ERROR;',
        '    const Entry& entry=entries[handle];if(offset>entry.length||length>entry.length-offset)return PICO_HTTP_IO_ERROR;',
        '#if defined(ESP8266)','    memcpy_P(destination,entry.bytes+offset,length);','#else','    memcpy(destination,entry.bytes+offset,length);','#endif',
        '    return static_cast<int>(length);','}','void asset_close(void*,int){}','}',
        'extern "C" {','const PicoHttpAsset pico_common_web_assets[] = {']
    for entry in entries:
        for route in (['/','/index.html'] if entry['source']=='index.html' else ['/'+entry['source']]):
            source.append('    {"'+route+'","'+entry['content_type']+'","gzip",nullptr,'+str(entry['length'])+',"'+entry['file_path']+'"},')
    source+=['};','const size_t pico_common_web_assets_count=sizeof(pico_common_web_assets)/sizeof(pico_common_web_assets[0]);',
        'const PicoHttpAssetIo pico_common_web_asset_io={asset_open,asset_read,asset_close};','}','#undef PICO_WEB_FLASH','']
    outputs[ROOT/'src/common_web_assets.cpp']='\n'.join(source).encode()
    outputs[ROOT/'firmware/web/manifest.json']=(json.dumps(dict(schema_version=1,assets=entries),indent=2)+'\n').encode()
    return outputs
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    outputs=products();stale=[p for p,data in outputs.items() if not p.is_file() or p.read_bytes()!=data]
    if args.check and stale:raise SystemExit('Stale common website assets: '+', '.join(str(p.relative_to(ROOT)) for p in stale))
    if not args.check:
        for p in stale:p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(outputs[p])
    print('Verified',len(ASSETS),'common browser assets,',sum(len(v) for p,v in outputs.items() if p.suffix=='.gz'),'compressed bytes')
if __name__=='__main__':main()
