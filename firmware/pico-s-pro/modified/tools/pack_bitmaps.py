"""Generate the lossless standalone OLED bitmap table from the original UI pixels."""
import re
from pathlib import Path
def pack(data):
    packed=bytearray()
    offset=0
    start=0
    def literals(end):
        for x in range(start,end,128):
            b=data[x:min(end,x+128)]
            packed.append(len(b)-1);packed.extend(b)
    while offset<len(data):
        length=0;dist=0
        for d in range(1,min(256,offset)+1):
            n=0
            while n<130 and offset+n<len(data) and data[offset+n]==data[offset+n-d]:n+=1
            if n>length:length,dist=n,d
        if length>=3:
            literals(offset)
            packed.extend([128+length-3,dist-1]);offset+=length;start=offset
        else:offset+=1
    literals(len(data))
    return packed

ROOT = Path(__file__).resolve().parents[1]
def main():
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = (ROOT/'src/ui/assets.c').read_text()
    table = bytearray()
    aliases = []
    for name, size, values in re.findall(r'const uint8_t (pico_ui_\w+)\[(\d+)\] = \{([^}]+)\}', source):
        if not 180 <= int(size) <= 480 or name in ('pico_ui_setup_6', 'pico_ui_setup_7'):
            continue
        data = bytes(int(x,16) for x in re.findall(r'0x([a-f0-9]+)', values))
        assert len(data) == int(size)
        aliases.append(f'#define {name} (pico_packed_pixels + {len(table)})')
        packed = pack(data)
        table.extend(len(data).to_bytes(2, 'little'))
        table.extend(packed)
    path = ROOT/'src/ui/packed_bitmaps.h'
    lines = ['/* Generated by tools/pack_bitmaps.py from assets.c. */',
             '#ifndef PICO_PACKED_BITMAPS_H', '#define PICO_PACKED_BITMAPS_H',
             f'extern const uint8_t pico_packed_pixels[{len(table)}];',
             '#ifdef PICO_DEFINE_PACKED_PIXELS', f'const uint8_t pico_packed_pixels[{len(table)}] = {{']
    for start in range(0,len(table),16):
        lines.append('    '+', '.join(f'0x{x:02x}' for x in table[start:start+16])+',')
    lines.extend(['};','#endif',*aliases,'#endif',''])
    content='\n'.join(lines)
    if args.check:
        if content != path.read_text(): raise SystemExit("Regenerate packed_bitmaps.h")
    else: path.write_text(content)

if __name__ == '__main__':
    main()
