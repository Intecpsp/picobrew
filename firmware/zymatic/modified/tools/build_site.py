"""Regenerate the embedded Zymatic site. Browsers decode its gzip representation."""
import gzip
from pathlib import Path

SITE = Path(__file__).resolve().parents[1] / "site"


def embed(source, symbol, section):
    payload = bytearray(gzip.compress(source.read_bytes(), compresslevel=9, mtime=0))
    payload[9] = 255  # platform-independent gzip OS byte
    rows = [", ".join(f"0x{value:02x}" for value in payload[i:i+16]) for i in range(0, len(payload), 16)]
    return (f"/* Generated by tools/build_site.py from site/{source.name}. */\n#pragma once\n"
            f"static const uint8_t {symbol}[] {section} = {{\n    " + ",\n    ".join(rows) + "\n};\n")


if __name__ == "__main__":
    (SITE / "zymatic_site.h").write_text(embed(SITE / "index.html", "zymatic_site", "ZYMATIC_SITE_SECTION"))
    (SITE / "zymatic_pair_js.h").write_text(embed(SITE / "pair.js", "zymatic_pair_js", "PROGMEM"))
    (SITE / "zymatic_favicon.h").write_text(embed(SITE / "favicon.ico", "zymatic_favicon", "PROGMEM"))
