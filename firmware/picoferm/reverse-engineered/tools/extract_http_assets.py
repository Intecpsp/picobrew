#!/usr/bin/env python3
"""Recover the complete PicoFerm HTML/CSS/JS prefix from the pinned OEM image."""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
IMAGE_SHA='08c34af891036494ae81d6f29e7495a475f67be977aa4effd3adde6fee4e9532'
def products():
    raw=(ROOT.parent/'oem/upstream/picoferm_0_2_7.bin').read_bytes()
    if hashlib.sha256(raw).hexdigest()!=IMAGE_SHA:raise ValueError('Unexpected OEM image')
    address=0x4024170c
    segments=json.loads((ROOT/'analysis/ghidra-layout.json').read_text())['segments']
    segment=next(s for s in segments if s['address']<=address<s['address']+s['size'])
    start=segment['offset']+address-segment['address'];text=raw[start:raw.index(0,start)]
    prefix=b'// Exact OEM 0x4024170c; generated by tools/extract_http_assets.py.\nstatic const char page_prefix[] FERM_HTTP_FLASH = R"FERM_HTML('
    suffix=b')FERM_HTML";\n'
    return {'assets/http-page-prefix.html':text,'src/http_assets.inc':prefix+text+suffix}
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for relative,content in products().items():
        path=ROOT/relative
        if args.check:
            if not path.is_file() or path.read_bytes()!=content:raise SystemExit('Stale HTTP asset: '+relative)
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(content)
    print('Verified complete 4272-byte OEM PicoFerm page prefix')
if __name__=='__main__':main()
