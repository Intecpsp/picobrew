def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    decoded = {}
    report = {'schema_version': 1, 'variants': {}}
    for variant in VARIANTS:
        raw = read_variant(variant)
        groups = {}
        for name, literals in TEXT.items():
            strings, provenance = [], []
            for address in literals:
                address -= 24 if variant == 'ssd1309' else 0
                pointer = struct.unpack_from('<I', raw, address - 0x20004000)[0]
                start = pointer - 0x20004000
                if not 0 <= start < len(raw):
                    raise ValueError('Message pointer outside OEM data')
                end = raw.find(b'\0', start, start + 512)
                if end < 0:
                    raise ValueError('Unterminated C message')
                value = raw[start:end]
                strings.append(value.decode('utf-8'))
                provenance.append({'literal': hex(address), 'address': hex(pointer),
                                   'sha256': hashlib.sha256(value + b'\0').hexdigest()})
            if decoded.setdefault(name, strings) != strings:
                raise ValueError('Workflow text differs between C display variants')
            groups[name] = provenance
        report['variants'][variant] = {'raw_sha256': VARIANTS[variant]['raw_sha256'], 'messages': groups}
    source = ['/* Original Pico C workflow strings; generated by tools/extract_workflow_text.py. */']
    for name, strings in decoded.items():
        source.append('static const char *const ' + name + '[] = {')
        source += ['    ' + json.dumps(value, ensure_ascii=False) + ',' for value in strings]
        source.append('};')
    products = {ROOT / 'src/ui/workflow_text.inc': '\n'.join(source) + '\n',
                ROOT / 'analysis/workflow-text.json': json.dumps(report, indent=2) + '\n'}
    for path, content in products.items():
        if options.check:
            if not path.exists() or path.read_text() != content:
                raise ValueError('C workflow text changed: ' + str(path))
        else:
            path.write_text(content)
    print(sum(len(values) for values in TEXT.values()), 'workflow strings checked in both C variants')


if __name__ == '__main__':
    main()
