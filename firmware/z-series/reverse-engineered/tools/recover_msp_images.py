#!/usr/bin/env python3
"""Generate owned MSP image descriptors from the hash-pinned Z119 image."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    manifest = json.loads((ROOT / "analysis/msp-protocol.json").read_text())
    original = (ROOT.parent / "oem/upstream/zseries_0_0_119.bin").read_bytes()
    if hashlib.sha256(original).hexdigest() != manifest["input_sha256"]:
        raise ValueError("Original Z119 image hash mismatch")
    header = '''// Generated by tools/recover_msp_images.py from preserved Z119 bytes.
// These are original MSP machine-code images, not reconstructed MSP source.
#pragma once
#include "zseries/msp_protocol.h"
namespace zseries { namespace oem {
extern const z_msp_image production_msp_image;
extern const z_msp_image unit_test_msp_image;
}} // namespace zseries::oem
'''
    lines = ['// Generated from preserved Z119; do not edit extracted bytes.',
             '#include "zseries/msp_images.hpp"',
             'namespace zseries { namespace oem {', 'namespace {']
    images = []
    for image in manifest["embedded_controller_images"]:
        name = image["role"].replace("-", "_")
        segments = []
        for index, segment in enumerate(image["segments"]):
            start, size = segment["file_offset"], segment["size_bytes"]
            data = original[start:start + size]
            if len(data) != size or hashlib.sha256(data).hexdigest() != segment["sha256"]:
                raise ValueError(f"Original MSP segment hash mismatch: {name}/{index}")
            symbol = f"{name}_{index}"
            lines.append(f"const std::uint8_t {symbol}[] = {{")
            for offset in range(0, size, 16):
                lines.append("    " + ",".join(f"0x{byte:02x}" for byte in data[offset:offset + 16]) + ",")
            lines.append("};")
            segments.append(f"    {{{segment['msp_address']},{size},{symbol}}},")
        lines.append(f"const z_msp_segment {name}_segments[] = {{")
        lines.extend(segments)
        lines.append("};")
        images.append(f"const z_msp_image {name}_msp_image = {{{len(segments)},{name}_segments}};")
    lines.append("} // namespace")
    lines.extend(images)
    lines.append("}} // namespace zseries::oem")
    # The C protocol header uses global fixed-width types; include <cstdint>
    # explicitly for the generated C++ std::uint8_t arrays.
    lines.insert(2, "#include <cstdint>")
    return {ROOT / "include/zseries/msp_images.hpp": header,
            ROOT / "src/msp_images.cpp": "\n".join(lines) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in generate().items():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f"Stale embedded MSP source: {path.relative_to(ROOT)}")
        else:
            path.write_text(text)
    print("Verified original production and diagnostic MSP image bytes" if args.check else
          "Generated production and diagnostic MSP image descriptors")


if __name__ == "__main__":
    main()
