#!/usr/bin/env python3
"""Extract the five evidenced Z119 font descriptors and packed grayscale data."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
from analyze_images import parse_image

ROOT=Path(__file__).resolve().parents[1]
IMAGE_SHA='d84e0106b69aa8a51ed62e56ae7215eb90908569e0f666b829e03fbc34c30b27'
FONTS=[('Font9x11',0x3f42b31c,9,11),('Font17x20',0x3f42ded4,17,20),
       ('Font14x16',0x3f437478,14,16),('Font8x16',0x3f43d718,8,16),('Font6x8',0x3f440f88,6,8)]

def outputs():
    data=(ROOT.parent/'oem/upstream/zseries_0_0_119.bin').read_bytes()
    if hashlib.sha256(data).hexdigest()!=IMAGE_SHA:raise ValueError('Unexpected OEM image')
    image=parse_image(data)
    def read(address,length):
        for segment in image['segments']:
            start=segment['load_address'];size=segment['size_bytes']
            if segment['memory_kind']=='DROM' and start<=address and address+length<=start+size:
                offset=segment['file_offset']+address-start;return data[offset:offset+length]
        raise ValueError('Font data outside original DROM')
    lines=['// Generated by tools/extract_display_fonts.py from the preserved Z119 image.',
           '// All bytes and descriptors are checked by --check; no OEM binary is needed at runtime.',
           '#include "zseries/display_fonts.hpp"','namespace zseries { namespace oem {','namespace {']
    records=[]
    for name,address,width,height in FONTS:
        descriptor=read(address,12);gw,gh,bitmap_address=struct.unpack('<3I',descriptor)
        if (gw,gh)!=(width,height):raise ValueError('Changed font metrics')
        bitmap_raw=read(bitmap_address,36);w,h,stride,left,top,right,bottom,pixels_address,size=struct.unpack('<9I',bitmap_raw)
        if (w,h,stride,left,top,right,bottom,size)!=(width*225,height,(width*225+1)//2,0,0,width*225-1,height-1,((width*225+1)//2)*height):
            raise ValueError('Unexpected packed font descriptor')
        pixels=read(pixels_address,size);array=name+'_pixels';font=name+'_font'
        lines.append('const std::uint8_t '+array+'[]={')
        for offset in range(0,len(pixels),24):lines.append('    '+','.join(f'0x{x:02x}' for x in pixels[offset:offset+24])+',')
        lines.extend(['};',f'const DisplayFont {font}{{{width},{height},DisplayBitmap{{{w},{h},{stride},DisplayRect{{0,0,{right},{bottom}}},{array},sizeof {array}}}}};'])
        records.append({'name':name,'font_address':f'0x{address:08x}','font_descriptor_sha256':hashlib.sha256(descriptor).hexdigest(),
            'glyph_width':width,'glyph_height':height,'glyph_count':225,'codepoint_first':32,'codepoint_last':255,'fallback_codepoint':256,
            'bitmap_address':f'0x{bitmap_address:08x}','bitmap_descriptor_sha256':hashlib.sha256(bitmap_raw).hexdigest(),
            'bitmap_width':w,'row_bytes':stride,'pixels_address':f'0x{pixels_address:08x}','pixels_bytes':size,'pixels_sha256':hashlib.sha256(pixels).hexdigest()})
    lines.extend(['} // namespace','const DisplayFont* display_font(DisplayFontId id) noexcept {','    switch(id){'])
    for name,_,_,_ in FONTS:lines.append(f'        case DisplayFontId::{name}:return &{name}_font;')
    lines.extend(['    }','    return nullptr;','}','}} // namespace zseries::oem',''])
    source='\n'.join(lines)
    report={'schema_version':1,'input_sha256':IMAGE_SHA,'format':'Packed 4-bit grayscale, even X in high nibble; source bitmap rows from high Y to low Y',
        'scope':'Exact font descriptor and pixel extraction; rendering behavior is validated separately. Names describe dimensions, not recovered vendor font names.',
        'fonts':records,'generated_source_sha256':hashlib.sha256(source.encode()).hexdigest(),'hardware_tested':False}
    return source,json.dumps(report,indent=2)+'\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    source,report=outputs();paths=[(ROOT/'src/display_fonts.cpp',source),(ROOT/'analysis/display-fonts.json',report)]
    for path,text in paths:
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit('Stale font extraction: '+str(path))
        else:path.write_text(text)
    print('Verified five Z119 font descriptors and 94,403 original packed pixel bytes' if args.check else 'Extracted five Z119 packed fonts')
if __name__=='__main__':main()
