#!/usr/bin/env python3
"""Embed the local browser client as reproducible gzip assets; no network access."""
import argparse
import gzip
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = [('index.html', 'text/html; charset=utf-8'),
          ('app.js', 'application/javascript; charset=utf-8'),
          ('style.css', 'text/css; charset=utf-8')]


def generate():
    parts = ['/* Generated by tools/embed_web.py from web/. Do not edit. */',
             '#include "picobrew/web_assets.h"', '']
    sizes = []
    for name, _ in ASSETS:
        raw = (ROOT / 'web' / name).read_bytes()
        packed = bytearray(gzip.compress(raw, compresslevel=9, mtime=0))
        # gzip.compress varies the OS header byte across supported Python versions.
        packed[9] = 255
        symbol = 'web_' + name.replace('.', '_')
        parts.append('/* ' + name + ' SHA-256: ' + hashlib.sha256(raw).hexdigest() + ' */')
        parts.append('static const uint8_t ' + symbol + '[] = {')
        parts.extend('    ' + ','.join('0x%02x' % b for b in packed[i:i+16]) + ','
                     for i in range(0, len(packed), 16))
        parts.append('};\n')
        sizes.append((name, len(raw), len(packed)))
    parts.append('const PicoHttpAsset pico_web_assets[] = {')
    parts.append('    {"/", "text/html; charset=utf-8", "gzip", web_index_html, sizeof(web_index_html)},')
    for name, content_type in ASSETS:
        symbol = 'web_' + name.replace('.', '_')
        parts.append('    {"/' + name + '", "' + content_type + '", "gzip", ' + symbol + ', sizeof(' + symbol + ')},')
    parts.extend(['};', 'const size_t pico_web_assets_count = sizeof(pico_web_assets) / sizeof(pico_web_assets[0]);', ''])
    return '\n'.join(parts), sizes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if committed generated bytes are stale')
    args = parser.parse_args()
    text, sizes = generate()
    destination = ROOT / 'src/local_web_assets.c'
    previous = destination.read_text() if destination.exists() else None
    if args.check and previous != text:
        parser.error('Embedded web assets are stale; run tools/embed_web.py')
    if not args.check and previous != text:
        destination.write_text(text)
    for name, raw, packed in sizes:
        print(f'{name}: {raw} bytes -> {packed} gzip bytes')
    print('Total embedded payload:', sum(size for _, _, size in sizes), 'bytes')


if __name__ == '__main__':
    main()
