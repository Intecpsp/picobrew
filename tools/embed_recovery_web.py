#!/usr/bin/env python3
"""Embed the independent recovery console as reproducible gzip assets."""
import argparse
import gzip
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = (("index.html", "text/html; charset=utf-8"),
          ("recovery.js", "application/javascript; charset=utf-8"),
          ("style.css", "text/css; charset=utf-8"))


def generate():
    header = '''/* Generated by tools/embed_recovery_web.py. */
#ifndef PICO_RECOVERY_WEB_ASSETS_H
#define PICO_RECOVERY_WEB_ASSETS_H
#include "picobrew/http_server.h"
#ifdef __cplusplus
extern "C" {
#endif
extern const PicoHttpAsset pico_recovery_assets[];
extern const size_t pico_recovery_assets_count;
#ifdef __cplusplus
}
#endif
#endif
'''
    parts = ['/* Generated by tools/embed_recovery_web.py. Do not edit. */', '#include "web_assets.h"']
    sizes = []
    for index, (name, _mime) in enumerate(ASSETS):
        raw = (ROOT / "recovery/web" / name).read_bytes()
        packed = bytearray(gzip.compress(raw, compresslevel=9, mtime=0))
        packed[9] = 255
        sizes.append((name, len(raw), len(packed)))
        parts.append(f"static const uint8_t asset_{index}[] = {{")
        for offset in range(0, len(packed), 16):
            parts.append("    " + ",".join(f"0x{value:02x}" for value in packed[offset:offset + 16]) + ",")
        parts.append("};")
    parts.append("const PicoHttpAsset pico_recovery_assets[] = {")
    for index, (name, mime) in enumerate(ASSETS):
        for path in (["/", "/index.html"] if index == 0 else ["/" + name]):
            parts.append(f'    {{"{path}", "{mime}", "gzip", asset_{index}, sizeof asset_{index}, NULL}},')
    parts.extend(["};", "const size_t pico_recovery_assets_count = sizeof pico_recovery_assets / sizeof pico_recovery_assets[0];", ""])
    return {ROOT / "recovery/web_assets.h": header.encode(),
            ROOT / "recovery/web_assets.c": "\n".join(parts).encode()}, sizes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs, sizes = generate()
    stale = [path for path, data in outputs.items() if not path.exists() or path.read_bytes() != data]
    if args.check and stale:
        parser.error("Recovery assets are stale; run tools/embed_recovery_web.py")
    if not args.check:
        for path in stale:
            path.write_bytes(outputs[path])
    for name, raw, packed in sizes:
        print(f"{name}: {raw} bytes -> {packed} gzip bytes")
    print("Embedded recovery gzip bytes:", sum(packed for _, _, packed in sizes))


if __name__ == "__main__":
    main()
