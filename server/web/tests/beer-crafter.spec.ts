import { test, expect } from '@playwright/test'

test('Beer Crafter charts, measurements and print sheet share the editable recipe', async ({
  page,
  request,
}) => {
  expect((await (await request.get('/api/v1/auth/session')).json()).demo).toBe(true)
  await page.goto('/#/recipes/new')
  await page.getByLabel('Recipe name').fill('Crafter trial')
  await page.getByLabel('Brewer', { exact: true }).selectOption('pico-s')
  await page.getByLabel('Recipe measurements').selectOption('us')
  await page.getByLabel('Batch size (US gal)').fill('1')
  await page.getByLabel('Recipe measurements').selectOption('metric')
  await expect(page.getByLabel('Batch size (L)')).toHaveValue('3.785411784')
  await page
    .getByRole('combobox', { name: 'Beer style', exact: true })
    .fill('American Light Lager (BJCP 2015 1A)')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByLabel('Grain', { exact: true }).fill('American Black Barley')
  await page.getByLabel('Weight (kg)').fill('0.8')
  await page.getByRole('button', { name: 'Hop slot 1', exact: true }).click()
  await page.getByLabel('Hop variety').fill('Cascade')
  await page.getByLabel('Weight (g)', { exact: true }).fill('10')
  await page.getByLabel('Yeast (optional)').fill('Wyeast 1007 German Ale')
  await page.getByLabel('Yeast amount (g)').fill('5')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('button', { name: 'Continue' }).click()
  const analysis = page.getByRole('region', { name: 'Recipe analysis' })
  await expect(analysis.getByRole('img', { name: 'Grain bill by weight' })).toBeVisible()
  await expect(analysis.getByRole('img', { name: 'Hop bill by weight' })).toBeVisible()
  await analysis.getByRole('button', { name: /American Black Barley/ }).focus()
  await expect(analysis.getByText('American Black Barley · 800 g')).toBeVisible()
  await expect(analysis.getByText(/1.028–1.040/)).toBeVisible()
  await page.getByRole('button', { name: 'Advanced editor' }).click()
  await expect(analysis.getByText('Original gravity', { exact: true })).toBeVisible()
  await expect(analysis.getByText('Bitterness', { exact: true })).toBeVisible()
  await expect(analysis.getByRole('button', { name: /^Scale / })).toHaveCount(0)
  await analysis.getByRole('button', { name: /American Black Barley/ }).focus()
  await expect(analysis.getByText('American Black Barley · 800 g')).toBeVisible()
  await page.getByLabel('Apply fermentation preset').selectOption('ale')
  await expect(page.getByLabel('Stage 1 days')).toHaveValue('10')
  await page.evaluate(() => window.dispatchEvent(new Event('beforeprint')))
  await page.emulateMedia({ media: 'print' })
  await expect(page.getByRole('article', { name: 'Crafter trial' })).toBeVisible()
  await expect(page.getByRole('article').getByText(/Primary fermentation/)).toBeVisible()
})
